export function finalizePage(pageId, page) {
	return {
		...page,
		title: clampTitle(stripResellerFromMeta(page.title)),
		description: clampDesc(stripResellerFromMeta(page.description)),
		heroImage: HERO_IMAGES[pageId],
	};
}

export function finalizePages(pages) {
	const out = {};
	for (const [id, page] of Object.entries(pages)) {
		out[id] = finalizePage(id, page);
	}
	return out;
}

